#!/usr/bin/env python3
"""Render the Features table of docs/PARITY.md from per-frontend manifests.

    python3 shared/walkthrough/features.py            # rewrite the table
    python3 shared/walkthrough/features.py --check    # exit 1 when it is stale
    python3 shared/walkthrough/features.py --print    # the table on stdout

The table was written by hand and was wrong in at least twelve cells after
one large change (#303). Now each frontend owns one file that says what it
does, and the table is those five files side by side:

    shared/walkthrough/feature-rows.json    the rows: id, label, evidence
    shared/walkthrough/features-gnome.json  GNOME (the root frontend)
    frontends/<name>/features.json          KDE, COSMIC, Niri, XFCE

To change a cell, edit that frontend's manifest and run this script. A
manifest must carry every row id and no other
(features.schema.json has the shape). tests/unit/test_parity_features.py
fails when the committed table is not what this prints.

A row may name `evidence`: something a machine can see. A cell that claims
"yes" for such a row must have it:
    {"walkthrough_screen": "<id>"}   docs/walkthrough/summary.json shows the
                                     screen for that frontend
    {"walkthrough_report": true}     the frontend has a walkthrough report
    {"workflow_job": "<file>", "name": "... {frontend} ..."}
                                     the workflow has a job with that name
"""

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
ROWS = os.path.join(HERE, "feature-rows.json")
PARITY = os.path.join(REPO, "docs", "PARITY.md")
SUMMARY = os.path.join(REPO, "docs", "walkthrough", "summary.json")
BEGIN = "<!-- features:begin (generated by shared/walkthrough/features.py; edit the manifests) -->"
END = "<!-- features:end -->"

# (id, column title, manifest path relative to the repository)
FRONTENDS = [
    ("gnome", "GNOME", "shared/walkthrough/features-gnome.json"),
    ("kde", "KDE", "frontends/kde/features.json"),
    ("cosmic", "COSMIC", "frontends/cosmic/features.json"),
    ("niri", "Niri", "frontends/niri/features.json"),
    ("xfce", "XFCE", "frontends/xfce/features.json"),
]


class FeatureError(ValueError):
    """A manifest, the row list or the document does not fit the contract."""


def _read(path):
    with open(path, encoding="utf-8") as stream:
        return json.load(stream)


def load_rows(path=ROWS):
    rows = _read(path)["rows"]
    ids = [row["id"] for row in rows]
    if len(ids) != len(set(ids)):
        raise FeatureError("feature-rows.json: a row id is listed twice")
    for row in rows:
        if not re.fullmatch(r"[a-z][a-z0-9_]*", row["id"]):
            raise FeatureError(f"feature-rows.json: bad id {row['id']!r}")
        if not row.get("label") or "|" in row["label"] or "\n" in row["label"]:
            raise FeatureError(f"feature-rows.json: bad label for {row['id']}")
    return rows


def check_manifest(frontend, manifest, rows):
    """Problems (strings) with one manifest against the row list."""
    problems = []
    if manifest.get("frontend") != frontend:
        problems.append(f"{frontend}: `frontend` is {manifest.get('frontend')!r}")
    features = manifest.get("features")
    if not isinstance(features, dict):
        return problems + [f"{frontend}: `features` must be an object"]
    wanted = [row["id"] for row in rows]
    for row_id in wanted:
        if row_id not in features:
            problems.append(f"{frontend}: no cell for `{row_id}`")
    for row_id, cell in features.items():
        if row_id not in wanted:
            problems.append(f"{frontend}: `{row_id}` is not a row of feature-rows.json")
        if not isinstance(cell, str) or not cell.strip():
            problems.append(f"{frontend}: `{row_id}` must be a non-empty string")
        elif "|" in cell or "\n" in cell:
            problems.append(f"{frontend}: `{row_id}` holds a `|` or a line break")
    return problems


def load_manifests(rows, repo=REPO):
    manifests, problems = {}, []
    for frontend, _title, relative in FRONTENDS:
        path = os.path.join(repo, relative)
        try:
            manifests[frontend] = _read(path)
        except (OSError, ValueError) as error:
            problems.append(f"{frontend}: {relative}: {error}")
            continue
        problems += check_manifest(frontend, manifests[frontend], rows)
    if problems:
        raise FeatureError("\n".join(problems))
    return manifests


def render(rows, manifests):
    """The Markdown table, without the markers."""
    lines = ["| Feature | " + " | ".join(title for _id, title, _path in FRONTENDS) + " |",
             "|---" * (len(FRONTENDS) + 1) + "|"]
    for row in rows:
        cells = [manifests[frontend]["features"][row["id"]].strip()
                 for frontend, _title, _path in FRONTENDS]
        lines.append(f"| {row['label']} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def claims_yes(cell):
    """Whether a cell says the frontend has the feature."""
    return re.match(r"yes\b", cell.strip(), re.IGNORECASE) is not None


def evidence_problems(rows, manifests, summary, workflow_text):
    """Cells that say "yes" for a row whose evidence is not there.

    summary: docs/walkthrough/summary.json as a dict.
    workflow_text(file) -> the text of .github/workflows/<file>.
    """
    problems = []
    for row in rows:
        evidence = row.get("evidence")
        if not evidence:
            continue
        for frontend, _title, _path in FRONTENDS:
            if not claims_yes(manifests[frontend]["features"][row["id"]]):
                continue
            if "walkthrough_screen" in evidence:
                screen = evidence["walkthrough_screen"]
                seen = (summary.get("screens", {}).get(screen) or {}).get(frontend)
                if seen != "yes":
                    problems.append(f"{frontend}: `{row['id']}` says yes, but the walkthrough "
                                    f"screen `{screen}` reads {seen!r}")
            if evidence.get("walkthrough_report"):
                if not (summary.get("frontends", {}).get(frontend) or {}).get("report"):
                    problems.append(f"{frontend}: `{row['id']}` says yes, but the walkthrough "
                                    f"has no report for it")
            if "workflow_job" in evidence:
                name = evidence["name"].replace("{frontend}", frontend)
                text = workflow_text(evidence["workflow_job"])
                if not re.search(rf"^\s+name: {re.escape(name)}\s*$", text, re.MULTILINE):
                    problems.append(f"{frontend}: `{row['id']}` says yes, but "
                                    f"{evidence['workflow_job']} has no job named {name!r}")
    return problems


def replace_table(document, table):
    """`document` with the text between the markers replaced by `table`."""
    if document.count(BEGIN) != 1 or document.count(END) != 1:
        raise FeatureError("docs/PARITY.md must hold the features markers once each")
    head, rest = document.split(BEGIN)
    _old, tail = rest.split(END)
    return f"{head}{BEGIN}\n\n{table}\n{END}{tail}"


def committed_table(document):
    if document.count(BEGIN) != 1 or document.count(END) != 1:
        raise FeatureError("docs/PARITY.md must hold the features markers once each")
    return document.split(BEGIN)[1].split(END)[0].strip("\n") + "\n"


def generated_table():
    rows = load_rows()
    return render(rows, load_manifests(rows))


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    try:
        table = generated_table()
        if "--print" in argv:
            sys.stdout.write(table)
            return 0
        with open(PARITY, encoding="utf-8") as stream:
            document = stream.read()
        if "--check" in argv:
            if committed_table(document) != table:
                print("docs/PARITY.md: the Features table is stale. "
                      "Run python3 shared/walkthrough/features.py", file=sys.stderr)
                return 1
            return 0
        with open(PARITY, "w", encoding="utf-8") as stream:
            stream.write(replace_table(document, table))
    except FeatureError as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
