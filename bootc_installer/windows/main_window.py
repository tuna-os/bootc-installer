# The app's own symbolic icons live in the gresource under this path.
# GTK only searches "<resource base path>/icons" on its own, and that base
# path follows the application id, so the Devel and variant ids
# (BOOTC_APP_ID) and the capture harness would never find them.
_RESOURCE_ICONS = "/org/bootcinstaller/Installer/icons"


def _register_resource_icons(widget):
    theme = Gtk.IconTheme.get_for_display(widget.get_display())
    if _RESOURCE_ICONS not in (theme.get_resource_path() or []):
        theme.add_resource_path(_RESOURCE_ICONS)


@Gtk.Template(resource_path="/org/bootcinstaller/Installer/gtk/window.ui")
class BootcWindow(Adw.ApplicationWindow):
    __gtype_name__ = "BootcWindow"

    carousel = Gtk.Template.Child()
    carousel_indicator_dots = Gtk.Template.Child()
    btn_back = Gtk.Template.Child()
    btn_next = Gtk.Template.Child()
    btn_exit = Gtk.Template.Child()
    btn_about = Gtk.Template.Child()
    btn_credits = Gtk.Template.Child()
    toasts = Gtk.Template.Child()

    def __init__(self, autoinstall_recipe: str | None = None, **kwargs):
        super().__init__(**kwargs)
        _register_resource_icons(self)

        logger.info("bootc Installer version: %s", _APP_VERSION)

        self.__autoinstall_recipe = autoinstall_recipe

        # this starts the builder and generates the widgets
        # to put in the carousel
        self.__builder = Builder(self)

        # system views
        self.__view_confirm = BootcConfirm(self)
        self.__view_progress = BootcProgress(self)
        self.__view_recovery_key = BootcRecoveryKey(self)
        self.__view_done = BootcDone(self)

        self.__install_is_encrypted = False
        self.__install_recovery_key = ""
        # The exit or cancel dialog that is open, so a second Ctrl+Q does
        # not stack another one.
        self.__open_dialog = None

        # sensitivity-tracking state for the header btn_next
        self.__next_page_widget = None
        self.__next_handlers = []
        # Handler ID for update_finals so we can disconnect it on rebuild.
        self.__update_finals_widget = None
        self.__update_finals_handler = None
        # Set when the window is destroyed. A destroyed window keeps its
        # carousel and pages while Python holds them, but nothing may move
        # them again (#353).
        self.__destroyed = False

        # this builds the UI with the widgets generated by the builder
        self.__build_ui()

        # connect system signals
        self.__connect_signals()

        # some variables to track state
        self.install_mode = 0

        # Autoinstall mode: skip the wizard and start immediately.
        if self.__autoinstall_recipe:
            GLib.idle_add(self._start_autoinstall)
        elif os.environ.get("BOOTC_PREVIEW_SCREEN"):
            GLib.idle_add(self.__apply_preview_screen)

    def __connect_signals(self):
        self.btn_back.connect("clicked", self.back)
        self.btn_next.connect("clicked", self.__on_header_next)
        self.btn_exit.connect("clicked", self.__on_exit_clicked)
        self.btn_about.connect("clicked", self.__on_about_clicked)
        self.btn_credits.connect("clicked", self.__on_credits_clicked)
        self.connect("close-request", self.__on_close_request)
        self.connect("destroy", self.__on_destroy)
        self.carousel.connect("page-changed", self.__on_page_changed)
        self.__reconnect_update_finals()
        self.__view_confirm.connect("installation-confirmed", self.on_installation_confirmed)
        self.__view_recovery_key.connect("recovery-key-acknowledged", self.__on_recovery_key_acknowledged)

        if os.environ.get("BOOTC_TEST"):
            self.carousel.connect("page-changed", self.__on_page_changed_test)
            GLib.timeout_add(600, self.__test_advance_first_page)

    def __reconnect_update_finals(self):
        """(Re-)connect update_finals to the last visible step's btn_next.

        Called after every carousel rebuild so that the correct step triggers
        finals collection when its Next button is clicked.
        """
        # Disconnect previous handler if any.
        if self.__update_finals_widget is not None and self.__update_finals_handler is not None:
            try:
                self.__update_finals_widget.btn_next.disconnect(self.__update_finals_handler)
            except Exception as e:
                logger.debug("Could not disconnect update_finals handler: %s", e)

        target = self.__last_step_widget
        if target is None and self.__builder.widgets:
            target = self.__builder.widgets[-1]

        if target is not None and hasattr(target, "btn_next"):
            self.__update_finals_handler = target.btn_next.connect("clicked", self.update_finals)
            self.__update_finals_widget = target

    def destroy(self):
        # gtk_window_destroy() hides and unrealizes the window, but it is
        # disposed (and "destroy" emitted) only when the last reference
        # goes, and Python holds one. So mark it here as well.
        self.__destroyed = True
        super().destroy()

    def __on_destroy(self, *args):
        self.__destroyed = True

    def __test_advance_first_page(self):
        if self.__destroyed:
            return GLib.SOURCE_REMOVE
        page = self.carousel.get_nth_page(0)
        if hasattr(page, "test_auto_advance"):
            page.test_auto_advance()
        return GLib.SOURCE_REMOVE

    def __on_page_changed_test(self, carousel, index):
        if self.__destroyed:
            return
        page = carousel.get_nth_page(int(index))
        if hasattr(page, "test_auto_advance"):
            # 700ms: enough for animations + update_finals() to have run
            GLib.timeout_add(700, self.__test_auto_advance, page)

    def __test_auto_advance(self, page):
        # The page may have left the screen, or the window may be gone,
        # while the timer ran. A destroyed window's carousel has no size:
        # every scroll_to() lands on page 0 again and emits page-changed,
        # so advancing it re-armed this timer forever (#353).
        if not self.__destroyed and self.__current_page() is page:
            page.test_auto_advance()
        return GLib.SOURCE_REMOVE

    def __current_page(self):
        position = round(self.carousel.get_position())
        if position >= self.carousel.get_n_pages():
            return None
        return self.carousel.get_nth_page(position)

    def rebuild_ui(self, mode=1):
        self.install_mode = mode
        self.__build_ui(True, mode)
        self.__reconnect_update_finals()

    def rebuild_ui_after_image(self):
        """Rebuild non-protected steps so they can react to the image selection."""
        self.__build_ui(True, self.install_mode)
        self.__reconnect_update_finals()

    def _is_offline_install(self) -> bool:
        """Whether the image is already here, so no network is needed.

        True for an explicit offline source in the recipe (local_imgref), or
        when fisherman's probe says the host booted from live media
        (`live.is_live`): an empty image then installs the running system.
        This used to look for /run/ostree-booted, which every installed
        ostree host has, so any bootc desktop counted as "offline".
        """
        recipe = self.recipe if hasattr(self, "recipe") else {}
        if recipe.get("local_imgref"):
            return True
        if Systeminfo.is_live():
            return True
        # An installed bootc computer can install its own system from its
        # bootc storage (#267, the confirm page offers it): the network
        # check must not stop it before that choice.
        return source_check.offers_reuse(Systeminfo.probe())

    def __step_context(self, current_widget=None):
        context = {
            "offline_install": self._is_offline_install(),
            # fisherman's tpm.usable (shared/probe/README.md), never an
            # inline probe: this was once a third copy of the TPM check.
            "has_tpm2": Systeminfo.has_tpm2(),
            "sys_recipe": self.recipe if hasattr(self, "recipe") else {},
            "leaf_count": getattr(self, "_image_leaf_count", 2),
            "disk_count": getattr(self, "_installable_disk_count", 2),
        }

        finals = []
        for widget in self.__builder.widgets:
            if widget is current_widget:
                break
            try:
                finals.append(widget.get_finals())
            except Exception as exc:
                logger.debug("(%s) Failed to collect step context finals: %s", getattr(widget, "__gtype_name__", type(widget).__name__), exc)
        context["finals"] = finals
        return context

    def image_to_download(self, before=None) -> str:
        """The image that the install pulls, as far as the steps before the
        page `before` have chosen it; "" when none has. The connection
        check probes the registry of this image first."""
        context = self.__step_context(before)
        try:
            from bootc_installer.utils.processor import Processor
            plan = Processor.image_plan(context["finals"], context["sys_recipe"])
        except Exception as error:  # noqa: BLE001 - a page asks; it must not fail
            logger.debug("no image plan yet: %s", error)
            return ""
        image = plan.get("install") or ""
        return image if isinstance(image, str) else ""

    def __build_ui(self, rebuild=False, mode=0):
        property_list = self.__builder.property_list
        context = self.__step_context()

        if rebuild:
            for view in (self.__view_confirm, self.__view_progress,
                         self.__view_recovery_key, self.__view_done):
                self.__remove_page(view)

        self.__last_step_widget = None

        if "VANILLA_FORCE_TOUR" not in os.environ:
            for i, widget in enumerate(self.__builder.widgets):
                if rebuild:
                    if "protected" in property_list[i]:
                        continue
                    else:
                        self.__remove_page(widget)
                if "custom_image" in property_list[i] and mode == 0:
                    continue
                if "default_image" in property_list[i] and mode == 1:
                    continue
                if getattr(widget, "skip_screen", False):
                    logger.info("(%s) Skipping screen (skip_screen=True)", getattr(widget, "__gtype_name__", type(widget).__name__))
                    continue
                if hasattr(widget, "should_show") and not widget.should_show(context):
                    logger.info("(%s) Skipping screen (should_show=False)", getattr(widget, "__gtype_name__", type(widget).__name__))
                    continue
                logger.info("(%s) Adding widget to carousel", getattr(widget, "__gtype_name__", type(widget).__name__))
                self.carousel.append(widget)
                self.__last_step_widget = widget
        else:
            self.__on_page_changed()

        self.carousel.append(self.__view_confirm)
        self.carousel.append(self.__view_progress)
        self.carousel.append(self.__view_recovery_key)
        self.carousel.append(self.__view_done)
        self.__contain_focus()

    def __remove_page(self, widget):
        """Take `widget` out of the carousel if it is there.

        A step that the last build skipped (should_show, skip_screen, the
        other install mode) is not a page. adw_carousel_remove() on it is a
        g_return_if_fail(): it logs Adwaita-CRITICAL and raises nothing, so
        a try/except here never caught it (#353).
        """
        if widget.get_parent() is self.carousel:
            self.carousel.remove(widget)
        else:
            logger.debug("(%s) not a carousel page: nothing to remove", getattr(widget, "__gtype_name__", type(widget).__name__))

    def __contain_focus(self):
        """Keep keyboard focus on the page the user can see (#310).

        Every page lives in the one carousel, so Tab used to walk off the
        visible page into the disk list, the passphrase entries and the Done
        page's Reboot button. `can-focus` on a page covers its descendants,
        and unlike `sensitive` it does not dim the page that slides in.
        """
        current = self.carousel.get_nth_page(int(self.carousel.get_position()))
        focus = self.get_focus()
        for index in range(self.carousel.get_n_pages()):
            page = self.carousel.get_nth_page(index)
            page.set_can_focus(page is current)
            if page is not current and focus is not None and (
                    focus is page or focus.is_ancestor(page)):
                # Focus stayed on the page that just left the screen.
                self.set_focus(None)
                focus = None

    def __on_page_changed(self, *args):
        cur_index = self.carousel.get_position()
        page = self.carousel.get_nth_page(cur_index)
        self.__contain_focus()

        logger.info("(%s) Page is changing...", getattr(page, "__gtype_name__", type(page).__name__))

        # Disconnect sensitivity tracking from previous page
        if self.__next_page_widget is not None:
            for h in self.__next_handlers:
                try:
                    self.__next_page_widget.btn_next.disconnect(h)
                except Exception as e:
                    logger.debug("Could not disconnect next button handler: %s", e)
            self.__next_page_widget = None
            self.__next_handlers = []

        is_final = page in [self.__view_progress, self.__view_recovery_key, self.__view_done]
        is_confirm = page == self.__view_confirm

        if is_confirm:
            logger.info("(%s) It is the confirm page", getattr(page, "__gtype_name__", type(page).__name__))
            self.btn_back.set_visible(True)
            self.btn_back.set_sensitive(True)
            self.carousel_indicator_dots.set_visible(False)
            self.btn_next.set_visible(False)
            return

        if is_final:
            logger.info("(%s) It is a final page", getattr(page, "__gtype_name__", type(page).__name__))
            self.btn_back.set_visible(False)
            self.btn_back.set_sensitive(False)
            self.carousel_indicator_dots.set_visible(False)
            self.btn_next.set_visible(False)
            return

        logger.info("(%s) It is not a final page", getattr(page, "__gtype_name__", type(page).__name__))
        self.btn_back.set_visible(cur_index != 0.0)
        self.btn_back.set_sensitive(cur_index != 0.0)
        self.carousel_indicator_dots.set_visible(cur_index != 0.0)

        if hasattr(page, "on_shown"):
            try:
                page.on_shown(self.__step_context(page))
            except Exception as exc:
                logger.warning("(%s) on_shown failed: %s", getattr(page, "__gtype_name__", type(page).__name__), exc)

        # Sync header btn_next with the current page's btn_next sensitivity only.
        # Visibility of the per-page btn_next is always false (hidden in favour of
        # the header button), so we must NOT mirror it — the header btn_next should
        # always be visible on step pages; only its sensitivity tracks the page.
        if hasattr(page, "btn_next"):
            self.btn_next.set_visible(True)
            self.btn_next.set_sensitive(page.btn_next.get_sensitive())

            def _sync(widget, _param):
                self.btn_next.set_sensitive(widget.get_sensitive())

            self.__next_handlers = [
                page.btn_next.connect("notify::sensitive", _sync),
            ]
            self.__next_page_widget = page
        else:
            self.btn_next.set_visible(False)

    def __on_header_next(self, *args):
        cur_index = int(self.carousel.get_position())
        page = self.carousel.get_nth_page(cur_index)
        if hasattr(page, "btn_next"):
            page.btn_next.emit("clicked")

    def __on_close_request(self, *args):
        self.request_quit()
        return True  # block the default close; dialog will quit() if confirmed

    def install_running(self) -> bool:
        """Whether fisherman (or the demo replay) is running now."""
        return self.__view_progress.is_running()

    def request_quit(self, *args):
        """Every way out of the application: the window's close button, the
        header's exit button and the app.quit action (Ctrl+Q). Ctrl+Q used
        to call Application.quit() directly, so one keystroke on the
        progress page removed the window and left fisherman on the disk
        (#309)."""
        self.__on_exit_clicked()

    def __is_done(self):
        # round(), not int(): while the carousel still slides to the done
        # page its position is a fraction below that page's index.
        cur_index = round(self.carousel.get_position())
        return self.carousel.get_nth_page(cur_index) is self.__view_done

    def __find_page_index(self, target_page):
        for index in range(self.carousel.get_n_pages()):
            if self.carousel.get_nth_page(index) is target_page:
                return index
        return -1

    def __go_to_page(self, target_page, animate=True):
        if target_page is None:
            return
        index = self.__find_page_index(target_page)
        if index < 0:
            return
        page = self.carousel.get_nth_page(index)
        if page is not None:
            self.carousel.scroll_to(page, animate)

    @staticmethod
    def __normalize_screen_name(name: str) -> str:
        return name.strip().lower().replace("_", "-")

    def __find_preview_target(self, screen_name: str):
        normalized = self.__normalize_screen_name(screen_name)
        static_pages = {
            "confirm": self.__view_confirm,
            "progress": self.__view_progress,
            "recovery-key": self.__view_recovery_key,
            "done": self.__view_done,
        }
        if normalized in static_pages:
            return static_pages[normalized]

        for widget in self.__builder.widgets:
            candidates = {
                getattr(widget, "_bootc_step_key", ""),
                getattr(widget, "_bootc_template", ""),
                getattr(widget, "__gtype_name__", type(widget).__name__),
            }
            normalized_candidates = {
                self.__normalize_screen_name(candidate)
                for candidate in candidates
                if candidate
            }
            if normalized in normalized_candidates:
                return widget
        return None

    def __apply_preview_screen(self):
        screen_name = os.environ.get("BOOTC_PREVIEW_SCREEN", "").strip()
        if not screen_name:
            return False

        target = self.__find_preview_target(screen_name)
        if target is None:
            logger.warning("Unknown BOOTC_PREVIEW_SCREEN=%s", screen_name)
            return False

        if target is self.__view_confirm:
            self.update_finals()
        elif target is self.__view_recovery_key:
            self.__view_recovery_key.set_recovery_key("demo-preview-recovery-key")
        elif target is self.__view_done:
            self.update_finals()
            self.__view_done.set_result(True, None)

        self.__go_to_page(target, animate=False)

        if target is self.__view_progress:
            if os.environ.get("BOOTC_DEMO"):
                self.__view_progress.start_demo()
            else:
                # Even without a demo install, configure the video so it plays
                self.__view_progress.configure_video_preview()

        return False

    def __finals_use_encryption(self):
        for final in getattr(self, "finals", []):
            encryption = final.get("encryption") if isinstance(final, dict) else None
            if not isinstance(encryption, dict):
                continue
            enc_type = encryption.get("type", "")
            if encryption.get("use_encryption") or enc_type not in ("", "none"):
                return True
        return False

    @staticmethod
    def __recipe_uses_encryption(recipe: dict) -> bool:
        encryption = recipe.get("encryption", {}) if isinstance(recipe, dict) else {}
        if not isinstance(encryption, dict):
            return False
        return encryption.get("type", "none") not in ("", "none")

    @staticmethod
    def _autoinstall_paths(path: str, in_flatpak: bool | None = None) -> list:
        """Where to look for the --autoinstall recipe.

        In a Flatpak the sandbox has its own /etc; the host's is at
        /run/host/etc (utils/recipe.py reads the system recipe there). A
        unit that names /etc/bootc-installer/autoinstall.json means the
        host's file, so that is tried first (#317).
        """
        if in_flatpak is None:
            in_flatpak = os.path.exists("/.flatpak-info")
        norm = os.path.normpath(path)
        if in_flatpak and os.path.isabs(norm) and (norm == "/etc" or norm.startswith("/etc/")):
            return ["/run/host" + norm, path]
        return [path]

    @staticmethod
    def _read_autoinstall_recipe(path: str, in_flatpak: bool | None = None):
        """(recipe, reason): the --autoinstall recipe, or None and the
        reason it cannot be used, in words for the result page."""
        reason = ""
        for candidate in BootcWindow._autoinstall_paths(path, in_flatpak):
            try:
                with open(candidate, encoding="utf-8") as recipe_file:
                    recipe = json.load(recipe_file)
            except OSError as exc:
                logger.warning("Failed to read install recipe %s: %s", candidate, exc)
                reason = reason or _("The recipe file {path} cannot be read: {error}").format(
                    path=path, error=exc.strerror or exc)
                continue
            except json.JSONDecodeError as exc:
                logger.warning("Install recipe %s is not valid JSON: %s", candidate, exc)
                return None, _("The recipe file {path} is not valid JSON: {error}").format(
                    path=path, error=exc)
            if not isinstance(recipe, dict):
                return None, _("The recipe file {path} does not hold a JSON object.").format(
                    path=path)
            return recipe, ""
        return None, reason

    @staticmethod
    def _load_autoinstall_recipe(path: str):
        """The --autoinstall recipe file, read here and handed to fisherman on
        stdin like any other recipe. None when it cannot be read."""
        return BootcWindow._read_autoinstall_recipe(path)[0]

    def _validate_autoinstall_recipe(self, recipe: dict) -> str:
        """"" when `recipe` can start, else the reason. The wizard checks a
        recipe field by field with `fisherman validate`; --autoinstall
        skipped every check, so a bad file failed inside the root process
        with a generic page (#317). When fisherman cannot be asked, the
        recipe starts: the install runs the same rules first."""
        if not Processor.recipe_names_disk(recipe):
            return _("The recipe names no installation disk.")
        from bootc_shared import validate as fisherman_validate

        from bootc_installer.utils import fisherman_runner
        try:
            if fisherman_runner.IN_FLATPAK and not fisherman_runner.stage_on_host():
                raise fisherman_validate.ValidateError("could not stage fisherman on the host")
            result = fisherman_validate.run(
                fisherman_validate.argv(fisherman_runner.fisherman_argv(), partial=False),
                recipe)
        except fisherman_validate.ValidateError as exc:
            logger.warning("Autoinstall: fisherman validate could not run: %s", exc)
            return ""
        from bootc_installer.utils import copy as copy_text
        lines = [
            fisherman_validate.render(problem, lambda key: copy_text.text(self, key))
            for problem in fisherman_validate.problems(result)
        ]
        lines = [line for line in lines if line]
        if not lines and result.get("valid") is False:
            lines = [_("fisherman did not accept the recipe.")]
        return " ".join(lines[:3])

    def __on_recovery_key_acknowledged(self, *args):
        # The user has the key now. Take it out of the log file, which a
        # later Show Log or bug report would otherwise carry (#316).
        self.__view_progress.scrub_log()
        self.__go_to_page(self.__view_done)

    def __on_about_clicked(self, *args):
        # Vendor and website come from the branding contract (branding.json,
        # then os-release); nothing here names a product.
        b = self.recipe.get("branding", {}) if hasattr(self, "recipe") else {}
        kwargs = dict(
            application_name=_("bootc Installer"),
            version=_APP_VERSION,
            license_type=Gtk.License.GPL_3_0,
        )
        if b.get("home_url"):
            kwargs["website"] = b["home_url"]
        if b.get("vendor"):
            kwargs["developer_name"] = b["vendor"]
        dialog = Adw.AboutDialog(**kwargs)
        dialog.present(self)

    def __on_credits_clicked(self, *args):
        from bootc_installer.windows.dialog_credits import BootcCreditsWindow
        BootcCreditsWindow(self).show()

    def __present_dialog(self, dialog, on_response):
        """Present one exit or cancel dialog at a time."""
        if self.__open_dialog is not None:
            return False

        def _response(dlg, response):
            self.__open_dialog = None
            on_response(dlg, response)

        dialog.connect("response", _response)
        self.__open_dialog = dialog
        dialog.present(self)
        return True

    def __on_exit_clicked(self, *args):
        running = self.install_running()
        if self.__is_done() and not running:
            self.get_application().quit()
            return
        dialog = Adw.AlertDialog(
            heading=_("Exit Installer?"),
            body=(_("An installation is in progress. If you exit now, the installer "
                    "stops it, and the disk can be left without a system that starts.")
                  if running else _("Any progress will be lost.")),
        )
        dialog.add_response("cancel", _("Cancel"))
        dialog.add_response("exit", _("Exit"))
        dialog.set_response_appearance("exit", Adw.ResponseAppearance.DESTRUCTIVE)
        dialog.set_default_response("cancel")
        dialog.set_close_response("cancel")
        self.__present_dialog(dialog, self.__on_exit_response)

    def __on_exit_response(self, dialog, response):
        if response == "exit":
            # Terminate fisherman if it's still running to avoid orphaned
            # root processes and partially-written disk state.
            self.__view_progress.terminate()
            self.get_application().quit()

    def request_cancel_install(self, *args):
        """The progress page's Cancel button: ask first, then stop the
        install and show the cancelled page (#299)."""
        if not self.install_running() or self.__view_progress.cancel_requested:
            return
        # During the copy of this computer's system the disk has not
        # changed yet (#267): say so, not that it can be left unusable.
        body = (copy_text.text(self, "progress_reuse_cancel")
                if self.__view_progress.copy_cancel else "")
        dialog = Adw.AlertDialog(
            heading=_("Cancel the installation?"),
            body=body or _("The installer stops the work on the disk. "
                           "The disk can be left without a system that starts."),
        )
        dialog.add_response("continue", _("Continue Installation"))
        dialog.add_response("stop", _("Cancel Installation"))
        dialog.set_response_appearance("stop", Adw.ResponseAppearance.DESTRUCTIVE)
        dialog.set_default_response("continue")
        dialog.set_close_response("continue")
        self.__present_dialog(dialog, self.__on_cancel_install_response)

    def __on_cancel_install_response(self, dialog, response):
        if response == "stop":
            self.__view_progress.cancel()

    def update_finals(self, *args):
        # collect all the finals
        if "VANILLA_FORCE_TOUR" not in os.environ:
            self.finals = self.__builder.get_finals()
        else:
            self.finals = json.loads(os.environ["VANILLA_FORCE_TOUR"])

        self.pretty_name, self.selected_icon = _extract_icon_and_name(self.finals)

        self.__view_confirm.update(self.finals)

    def on_installation_confirmed(self, *args):
        # One install at a time. A second confirmation (a handler connected
        # twice, a second click on Try Again) used to start a second root
        # fisherman on the same disk (#307, #308).
        if self.install_running():
            logger.warning("Install already running: ignoring a second confirmation")
            return
        self.__install_is_encrypted = self.__finals_use_encryption()
        self.__install_recovery_key = ""

        # Apply any hostname edit the user made on the confirm screen.
        hostname_override = self.__view_confirm.get_hostname_override()
        if hostname_override:
            for final in self.finals:
                if isinstance(final, dict) and "hostname" in final:
                    final["hostname"] = hostname_override
                    break

        if os.environ.get("BOOTC_DEMO"):
            self.__go_to_page(self.__view_progress)
            self.__view_progress.start_demo()
            return

        try:
            recipe = Processor.gen_install_recipe(
                "",
                self.finals,
                self.recipe,
            )
            # The install source of the confirm page: the download, or this
            # computer's system from its bootc storage (#267).
            recipe = self.__view_confirm.apply_source(recipe)
        except ValueError as error:
            logger.error("Refusing invalid installation recipe: %s", error)
            self.toast(_("The installation storage configuration is invalid. Check the system recipe."), timeout=6)
            self.__view_confirm.rearm()
            return
        # The disk page keeps Next disabled without a disk, but this is the
        # last point before fisherman runs as root, so check what was actually
        # written. Starting with an empty disk only fails inside fisherman,
        # with an error a user cannot act on (#154).
        if not Processor.recipe_names_disk(recipe):
            logger.error("Refusing to install: the recipe names no target disk")
            self.toast(_("No installation disk is selected. Go back and choose a disk."), timeout=6)
            self.__view_confirm.rearm()
            return
        # Go to the progress page by name, not with next(): from the done
        # page (Try Again) next() does nothing, and the install ran behind
        # the failure page (#307).
        self.__go_to_page(self.__view_progress)
        self.__view_progress.start(recipe)

    def retry_installation(self, *args):
        """Try Again on the done page: the same install once more."""
        if self.install_running():
            logger.warning("Install already running: ignoring Try Again")
            return
        if self.__autoinstall_recipe:
            # No wizard ran, so there are no finals to build a recipe from.
            self._start_autoinstall()
            return
        self.on_installation_confirmed()

    def _start_autoinstall(self):
        """Called via GLib.idle_add when --autoinstall was passed.

        Navigates directly to the progress view and starts fisherman with the
        pre-built recipe, bypassing the entire wizard. The file is read here;
        fisherman gets its content on stdin.
        """
        if self.install_running():
            return False
        logger.info(f"Autoinstall: starting with recipe {self.__autoinstall_recipe}")
        recipe, reason = self._read_autoinstall_recipe(self.__autoinstall_recipe)
        if recipe is not None:
            reason = self._validate_autoinstall_recipe(recipe)
        self.__install_is_encrypted = self.__recipe_uses_encryption(recipe or {})
        self.__install_recovery_key = ""
        if reason:
            # Nothing was started. Say why on the result page.
            logger.error("Autoinstall refused: %s", reason)
            self.set_installation_result(False, None, message=reason)
            return False

        self.__go_to_page(self.__view_progress, animate=False)
        self.__view_progress.start(recipe)
        return False  # remove idle callback

    def next(self, widget=None, fn=None, *args):
        if self.__destroyed:
            return
        logger.info("Going to next page")

        cur_index = self.carousel.get_position()
        if int(cur_index) >= self.carousel.get_n_pages() - 1:
            logger.info(f"Already on last page ({int(cur_index)}), ignoring next()")
            return
        page = self.carousel.get_nth_page(cur_index)
        if getattr(page, "delta", False):
            logger.info(f"Removing deltas of page {int(cur_index)}")
            page.del_deltas()
        logger.info(f"Next page is {int(cur_index + 1)}")

        if fn is not None:
            logger.info("Executing page's custom function")
            fn()
            logger.info("Finished executing page's custom function")

        page = self.carousel.get_nth_page(cur_index + 1)
        self.carousel.scroll_to(page, True)
        if getattr(page, "delta", False):
            logger.info(f"Generating deltas of page {int(cur_index + 1)}")
            page.gen_deltas()

    def back(self, *args):
        if self.__destroyed:
            return
        logger.info("Going to previous page")

        cur_index = self.carousel.get_position()
        page = self.carousel.get_nth_page(cur_index)
        if getattr(page, "delta", False):
            page.del_deltas()
        logger.info(f"Previous page is {int(cur_index - 1)}")

        page = self.carousel.get_nth_page(cur_index - 1)
        self.carousel.scroll_to(page, True)
        if getattr(page, "delta", False):
            page.gen_deltas()

    def toast(self, message, timeout=3):
        toast = Adw.Toast.new(message)
        toast.props.timeout = timeout
        self.toasts.add_toast(toast)

    def set_installation_result(self, result, terminal, boot_id="", recovery_key="", elapsed_secs=0,
                                exit_code=None, cancelled=False, message=None, error=None,
                                receipt=None):
        """`error` is fisherman's last `error` event ({"message", "code",
        "field"}) when the install failed with one; the done page shows it.
        `receipt` is the install's `receipt` event as the parser kept it."""
        if result:
            logger.info("Installation complete!")
        elif cancelled or exit_code == 130:
            logger.warning("Installation cancelled (exit code %s)", exit_code)
        else:
            logger.error("Installation failed! (exit code %s)", exit_code)

        self.__install_recovery_key = recovery_key or self.__install_recovery_key

        # Pass installed image ref to done screen so it can schedule a registry warmup.
        image_ref = None
        for f in getattr(self, "finals", []):
            if isinstance(f, dict):
                image_ref = f.get("custom_image") or f.get("selected_image")
                if image_ref:
                    break

        self.__view_done.set_result(result, terminal, boot_id, elapsed_secs,
                                    image_ref=image_ref, exit_code=exit_code,
                                    cancelled=cancelled, message=message, error=error,
                                    receipt=receipt)

        if result and self.__install_is_encrypted and self.__install_recovery_key:
            # Only show the recovery key screen when fisherman actually emitted a
            # random recovery key (tpm2-luks only). luks-passphrase and
            # tpm2-luks-passphrase use the user's own passphrase — no random key
            # is generated, so there is nothing to display here.
            self.__view_recovery_key.set_recovery_key(self.__install_recovery_key)
            self.__go_to_page(self.__view_recovery_key)
            return

        self.__go_to_page(self.__view_done)
